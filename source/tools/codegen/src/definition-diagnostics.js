/** biome-ignore-all lint/correctness/noNodejsModules: Node-side tooling, never bundled for a browser — the built-ins are the point. */
/**
 * schemas/definition-diagnostics.yaml -> @hatua/model and the Go SDK.
 *
 * The document's diagnostics, not the expression language's. Those live in
 * `schemas/diagnostics.yaml` and are emitted by tools/expression into the
 * expressions subtree of both languages, which is deliberately ignorant of
 * manifests, documents and Boards — so a code about a Fork's branches cannot go
 * there.
 *
 * Emitting Go source rather than embedding the YAML is forced for the reason
 * tools/expression gives: `go:embed` cannot reach outside its own module, and
 * the Go SDK is a separate one.
 */
import fs from 'node:fs'
import path from 'node:path'
import { parse } from 'yaml'

const q = (value) => JSON.stringify(value)

/** SCREAMING_SNAKE -> PascalCase, for Go identifiers. */
const pascal = (value) =>
  value
    .toLowerCase()
    .split('_')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')

const BANNER = [
  '// Code generated by tools/codegen. DO NOT EDIT.',
  '// Source: schemas/definition-diagnostics.yaml',
  '',
]

export function readDefinitionDiagnostics(schemasDir) {
  const file = path.join(schemasDir, 'definition-diagnostics.yaml')
  const codes = parse(fs.readFileSync(file, 'utf8')).codes ?? []
  if (codes.length === 0) throw new Error('definition-diagnostics.yaml declares no codes')

  const seen = new Set()
  for (const entry of codes) {
    if (!/^[A-Z][A-Z0-9_]*$/.test(entry.code ?? '')) {
      throw new Error(`definition-diagnostics.yaml: bad code ${q(entry.code)}`)
    }
    if (seen.has(entry.code)) {
      throw new Error(`definition-diagnostics.yaml: ${entry.code} is declared twice`)
    }
    seen.add(entry.code)
    if (!['edit', 'publish'].includes(entry.blocks)) {
      throw new Error(`${entry.code}: blocks must be edit or publish`)
    }
    if (!entry.message) throw new Error(`${entry.code}: missing message`)
  }
  return codes
}

export function definitionDiagnosticsToTs(codes) {
  return [
    ...BANNER,
    '/**',
    ' * What a diagnostic stops. `publish` never blocks editing (ADR-0009);',
    ' * `edit` is reserved for what ordinary building cannot produce.',
    ' */',
    "export type Blocks = 'edit' | 'publish'",
    '',
    'export type DefinitionCode =',
    ...codes.map((entry) => `  | ${q(entry.code)}`),
    '',
    'export interface DefinitionDiagnosticSpec {',
    '  readonly code: DefinitionCode',
    '  readonly blocks: Blocks',
    '  /** Template. `{name}` holes are filled by `formatDefinitionMessage`. */',
    '  readonly message: string',
    '}',
    '',
    '/**',
    ' * `blocks` is part of the shared contract. A code that stopped Publish here',
    ' * and merely informed in Go would let a workflow publish from one builder',
    ' * and not another.',
    ' */',
    'export const DEFINITION_DIAGNOSTICS: Record<DefinitionCode, DefinitionDiagnosticSpec> = {',
    ...codes.map(
      (entry) =>
        `  ${entry.code}: { code: ${q(entry.code)}, blocks: ${q(entry.blocks)}, message: ${q(entry.message.trim())} },`,
    ),
    '}',
    '',
  ].join('\n')
}

export function definitionDiagnosticsToGo(codes) {
  return [
    ...BANNER,
    'package hatua',
    '',
    '// Blocks says what a diagnostic stops: publish never blocks editing',
    '// (ADR-0009), and edit is reserved for what ordinary building cannot',
    '// produce.',
    'type Blocks string',
    '',
    'const (',
    '\tBlocksEdit    Blocks = "edit"',
    '\tBlocksPublish Blocks = "publish"',
    ')',
    '',
    '// DefinitionCode is a stable diagnostic identifier, shared with TypeScript.',
    'type DefinitionCode string',
    '',
    'const (',
    ...codes.map((entry) => `\tCode${pascal(entry.code)} DefinitionCode = ${q(entry.code)}`),
    ')',
    '',
    '// DefinitionDiagnosticSpec is one declared code.',
    'type DefinitionDiagnosticSpec struct {',
    '\tCode    DefinitionCode',
    '\tBlocks  Blocks',
    '\t// Message is a template; {name} holes are filled by FormatDefinitionMessage.',
    '\tMessage string',
    '}',
    '',
    '// DefinitionDiagnostics is the declaration. Blocks is part of the shared',
    '// contract: a code that stopped Publish in TypeScript and merely informed',
    '// here would let a workflow publish from one builder and not another.',
    'var DefinitionDiagnostics = map[DefinitionCode]DefinitionDiagnosticSpec{',
    ...codes.map(
      (entry) =>
        `\tCode${pascal(entry.code)}: {Code: Code${pascal(entry.code)}, Blocks: ${entry.blocks === 'edit' ? 'BlocksEdit' : 'BlocksPublish'}, Message: ${q(entry.message.trim())}},`,
    ),
    '}',
    '',
  ].join('\n')
}
